// ── LOAD FUNCTION ─────────────────────────────────────────────────────────────

/**
 * Loads all seed data into localStorage.
 * Skips items that already exist (by ID).
 * Returns a summary of what was loaded.
 */
export function loadSeedData(): { personas: number; hooks: number; bodies: number; angles: number; creatives: number; rules: number } {
  const KEYS = {
    personas:  "sm_personas",
    hooks:     "sm_hooks",
    bodies:    "sm_bodies",
    angles:    "sm_angles",
    creatives: "sm_creatives",
    rules:     "sm_rules",
  };

  function load<T extends { id: string }>(key: string, items: T[]): number {
    const existing: T[] = JSON.parse(localStorage.getItem(key) || "[]");
    const existingIds = new Set(existing.map(x => x.id));
    const newItems = items.filter(x => !existingIds.has(x.id));
    if (newItems.length > 0) {
      localStorage.setItem(key, JSON.stringify([...existing, ...newItems]));
    }
    return newItems.length;
  }

  return {
    personas:  load(KEYS.personas,  SEED_PERSONAS),
    hooks:     load(KEYS.hooks,     SEED_HOOKS),
    bodies:    load(KEYS.bodies,    SEED_BODIES),
    angles:    load(KEYS.angles,    SEED_ANGLES),
    creatives: load(KEYS.creatives, SEED_CREATIVES),
    rules:     load(KEYS.rules,     SEED_RULES),
  };
}
